#!/usr/bin/env python3
from __future__ import annotations
import pathlib, sys
ROOT=pathlib.Path(__file__).resolve().parents[1]
def text(p): return (ROOT/p).read_text()
checks=[]
def check(n,c): checks.append((n,c))
cargo=text('Cargo.toml'); core=text('crates/sparkbridge-core/src/lib.rs'); protocol=text('crates/sparkbridge-protocol/src/lib.rs'); cas=text('crates/sparkbridge-cas/src/lib.rs'); snap=text('crates/sparkbridge-snapshot/src/lib.rs'); server=text('apps/sparkbridge-server/src/main.rs'); store=text('apps/sparkbridge-server/src/store.rs'); executor=text('apps/sparkbridge-executor/src/main.rs'); config=text('crates/sparkbridge-config/src/lib.rs')
check('workspace version 0.12.0','version = "0.12.0"' in cargo)
check('protocol is 1.10','PROTOCOL_MINOR: u16 = 10' in protocol)
check('CAS and snapshot crates are workspace members','crates/sparkbridge-cas' in cargo and 'crates/sparkbridge-snapshot' in cargo)
check('SHA-256 CAS addressing','sha256:' in cas and 'Sha256' in cas)
check('CAS verifies claimed digest','CAS digest mismatch' in cas)
check('CAS writes use temporary file + fsync + rename','.tmp' in cas and 'sync_all' in cas and 'fs::rename' in cas)
check('CAS object reads verify stored digest','failed digest verification' in cas)
check('CAS fsck primitive exists','fsck_object' in cas)
check('snapshot performs before/after stability scan','let before = scan_stamps' in snap and 'let after = scan_stamps' in snap)
check('snapshot retries busy workspaces','SNAPSHOT_BUSY' in snap and 'max_retries' in snap)
check('Git state is stable across scan','git_before' in snap and 'git_after' in snap)
check('Git inspection is read-only','ls-files' in snap and 'write-tree' not in snap)
check('custom sparkbridge ignore exists','.sparkbridgeignore' in snap)
check('symlinks are recorded without following','symlink_target' in snap and 'read_link' in snap)
check('non UTF-8 logical paths are rejected','NON_UTF8_PATH' in snap)
check('Windows reserved names are rejected','WINDOWS_RESERVED_PATH' in snap)
check('case collisions are rejected','PLATFORM_PATH_COLLISION' in snap)
check('snapshot file-size bound exists','max_file_bytes' in snap and 'snapshot_max_file_bytes' in config)
check('workspace roots confine snapshot source','workspace_roots' in config and 'authorize_workspace' in executor)
check('missing-object negotiation exists','cas/missing' in server and 'MissingObjectsRequest' in protocol)
check('incremental upload asks for only missing digests','missing.missing' in executor)
check('zstd CAS transfer exists','CONTENT_ENCODING' in server and 'zstd::stream::encode_all' in executor)
check('CAS endpoint remains on mTLS fabric','cas/{digest}' in server and 'fabric_app' in server)
check('snapshot registration requires authenticated node','register_snapshot' in server and 'authenticate(&state, id, &headers)' in server)
check('snapshot registration requires manifest in CAS','snapshot manifest is not present in CAS' in server)
check('snapshot registration verifies referenced objects','snapshot references missing CAS object' in server)
check('snapshot registry is durable SQLite','CREATE TABLE IF NOT EXISTS snapshots' in store)
check('schema migrated through v8','SCHEMA_VERSION: u32 = 9' in store and 'PRAGMA user_version = 9' in store)
check('executor explicit snapshot command exists','snapshot: Option<PathBuf>' in executor and 'snapshot_and_upload' in executor)
check('admin snapshot listing exists','/api/v1/admin/snapshots' in server)
check('workspace feature negotiation exists','ITERATION_4_WORKSPACES' in core and 'ContentAddressedStorage' in core)
failed=[n for n,c in checks if not c]
for n,c in checks: print(('PASS' if c else 'FAIL')+': '+n)
if failed:
 print(f'\n{len(failed)} snapshot/CAS invariant(s) failed',file=sys.stderr); sys.exit(1)
print(f'\nCAS + Snapshot audit passed: {len(checks)} invariants')
